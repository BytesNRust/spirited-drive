/* the characters of `name` the font has, up to as many as fit across at scale 1 */
static size_t drawable(const char *name, char *out, size_t cap)
{
    size_t n = 0;
    for (const unsigned char *c = (const unsigned char *)name; *c != '\0' && n + 1 < cap; c++)
        if (*c >= FIRST && *c <= LAST) out[n++] = (char)*c;
    out[n] = '\0';
    while (n > 0 && out[n - 1] == ' ') out[--n] = '\0';
    return n;
}

static void glyph(uint8_t *px, unsigned char c, int x0, int y0, int scale)
{
    const uint8_t *rows = FONT[c - FIRST];
    for (int r = 0; r < GLYPH_H; r++)
        for (int col = 0; col < GLYPH_W; col++) {
            if (!(rows[r] & (0x10 >> col))) continue;
            for (int dy = 0; dy < scale; dy++)
                for (int dx = 0; dx < scale; dx++) {
                    const int x = x0 + col * scale + dx, y = y0 + r * scale + dy;
                    if (x >= 0 && x < CAR_CARD_W && y >= 0 && y < CAR_CARD_H) px[y * CAR_CARD_W + x] = INK_TEXT;
                }
        }
}

/* the name centred, at the largest scale up to MAX_SCALE that fits between the margins; cut at scale 1 when even that does not */
static void text(uint8_t *px, const char *name)
{
    char s[128];
    size_t n = drawable(name, s, sizeof s);
    const int room = CAR_CARD_W - 2 * MARGIN;
    int scale = MAX_SCALE;
    while (scale > 1 && (int)n * ADVANCE * scale - scale > room) scale--;
    while (n > 0 && (int)n * ADVANCE * scale - scale > room) s[--n] = '\0';
    const int width = (int)n * ADVANCE * scale - scale, x0 = (CAR_CARD_W - width) / 2, y0 = (CAR_CARD_H - GLYPH_H * scale) / 2;
    for (size_t i = 0; i < n; i++) glyph(px, (unsigned char)s[i], x0 + (int)i * ADVANCE * scale, y0, scale);
}

int car_card_generic_png(const char *name, uint8_t **png, size_t *len, ExchangeError *err)
{
    uint8_t *px = calloc((size_t)CAR_CARD_W * CAR_CARD_H, 1), palette[768] = { 0 };
    if (px == NULL) { exchange_fail(err, "out of memory"); return 0; }
    for (int y = 0; y < CAR_CARD_H; y++)
        for (int x = 0; x < CAR_CARD_W; x++)
            if (x < FRAME || y < FRAME || x >= CAR_CARD_W - FRAME || y >= CAR_CARD_H - FRAME) px[y * CAR_CARD_W + x] = INK_FRAME;
    text(px, name);
    memcpy(palette, PALETTE, sizeof PALETTE);
    const PngResult r = png_write_indexed(px, CAR_CARD_W, CAR_CARD_H, palette, png, len);
    free(px);
    if (r != PNG_OK) { exchange_fail(err, "card.png: %s", png_result_str(r)); return 0; }
    return 1;
}

int car_card_generic(const char *piece_dir, int force, ExchangeError *err)
{
    char path[PATH_MAX], why[160];
    if (!fsio_find_ci(piece_dir, "mod.ini", path, sizeof path)) { exchange_fail(err, "%s has no mod.ini: not a car piece", piece_dir); return 0; }
    size_t size = 0;
    uint8_t *card = fsio_read_file(path, &size, err), *png = NULL;
    if (card == NULL) return 0;
    ModInfo info;
    const int parsed = mod_ini_parse(card, size, &info, why, sizeof why);
    free(card);
    if (!parsed) { exchange_fail(err, "%s: %s", path, why); return 0; }
    if (info.type != MOD_TYPE_CAR) { exchange_fail(err, "%s: not a car piece (type=car)", path); return 0; }
    size_t len = 0;
    if (!car_card_generic_png(info.name, &png, &len, err)) return 0;
    snprintf(path, sizeof path, "%s/card.png", piece_dir);
    const int ok = fsio_write_file(path, png, len, force, err);
    free(png);
    if (ok) printf("car card: %s, the generic card of %s\n", path, info.name);
    return ok;
}

int car_card_command(int argc, char **argv, ExchangeError *err)
{
    const char *piece = NULL;
    int generic = 0, force = 0;
    for (int i = 2; i < argc; i++) {
        if (strcmp(argv[i], "--generic") == 0) generic = 1;
        else if (strcmp(argv[i], "--force") == 0) force = 1;
        else if (argv[i][0] != '-' && piece == NULL) piece = argv[i];
        else { exchange_fail(err, "unexpected argument '%s'; %s", argv[i], USAGE); return 0; }
    }
    if (piece == NULL || !generic) { exchange_fail(err, USAGE); return 0; }
    return car_card_generic(piece, force, err);
}
