SoundStep sound_voice_step(uint32_t rate, int32_t cents, uint32_t mix_rate)
{
    int32_t at = (int32_t)((uint32_t)cents + CENTS_BIAS);
    int32_t top = CENTS_TOP;
    uint32_t shift = CENTS_FIRST_SHIFT;
    while (at < top) {
        top -= CENTS_STEPS;
        shift++;
    }
    const int32_t index = at - top;
    /* past the table the original reads on: zeros in the exe's image, and at run time row 0 of the
     * volume table 004984f6 builds right after it (zeros too, up to index 1455) */
    const uint64_t product = (uint64_t)rate * (index < CENTS_STEPS ? CENTS[index] : 0);
    const uint32_t freq = (uint32_t)(product >> (shift & 31));  /* shrd takes cl mod 32 */
    SoundStep s = { 0, 0, 0 };
    if (mix_rate == 0) return s;  /* port guard: the original divides by 0 */
    s.whole = (freq / mix_rate) & STEP_WHOLE_MASK;
    const uint32_t rest = freq - s.whole * mix_rate;
    s.fraction = (uint32_t)(((uint64_t)rest << STEP_FRACTION_BITS) / mix_rate) << 8;
    s.step = s.whole << STEP_FRACTION_BITS | s.fraction >> 8;
    return s;
}

enum { PITCH_CENTRE = 0x40, CENTS_PER_UNIT = 100, PITCH_STEPS_SHIFT = 6 };

int32_t sound_pitch_cents(int32_t pitch, int32_t range, int32_t base)
{
    const int32_t span = (int32_t)(((uint32_t)pitch - PITCH_CENTRE) * ((uint32_t)range * CENTS_PER_UNIT));
    return (int32_t)((uint32_t)(span / (1 << PITCH_STEPS_SHIFT)) + (uint32_t)base);  /* sbb / sar: rounds toward 0 */
}

enum { PAN_CENTRE = 0x40, GAIN_FULL = 0x7f, PAN_SIDE_SPAN = 0x3e, GAIN_SHIFT = 10 };

SoundGains sound_pan_gains(uint32_t pan, uint32_t volume)
{
    uint32_t left = GAIN_FULL, right = GAIN_FULL;
    if (pan < PAN_CENTRE)
        right = pan << 1;
    else if (pan > PAN_CENTRE)
        left = (uint32_t)((GAIN_FULL - pan) * GAIN_FULL) / PAN_SIDE_SPAN;  /* 32-bit, as mul then edx = 0 */
    /* past 32 bits the original's div faults; the port keeps the low word */
    const SoundGains g = { (uint32_t)((uint64_t)left * volume / GAIN_FULL) << GAIN_SHIFT,
                           (uint32_t)((uint64_t)right * volume / GAIN_FULL) << GAIN_SHIFT };
    return g;
}

/* 004c91ec[row][sample]: (int8) sample x 2 x row */
static int32_t volume_row(uint32_t gain, uint8_t sample)
{
    return (int32_t)((uint32_t)(int32_t)(int8_t)sample * 2u * (gain >> GAIN_SHIFT));
}

static void advance(MixVoice *v, uint32_t *pos, uint32_t *frac)
{
    const uint32_t f = *frac + v->step.fraction;
    *pos += v->step.whole + (f < *frac);
    *frac = f;
}

void sound_mix_mono8(MixVoice *v, int32_t *acc, uint32_t count)
{
    uint32_t pos = v->pos, frac = v->frac;
    for (uint32_t i = 0; i < count; i++) {
        const uint8_t s = v->data[pos];
        acc[2 * i] = (int32_t)((uint32_t)acc[2 * i] + (uint32_t)volume_row(v->gains.left, s));
        acc[2 * i + 1] = (int32_t)((uint32_t)acc[2 * i + 1] + (uint32_t)volume_row(v->gains.right, s));
        advance(v, &pos, &frac);
    }
    v->pos = pos;
    v->frac = frac;
}

enum { SAMPLE16_SHIFT = 7 };

static int32_t sample16(const uint8_t *data, uint32_t frame)
{
    return (int16_t)(uint16_t)(data[2 * frame] | data[2 * frame + 1] << 8);
}

/* imul / sar 7 */
static uint32_t scaled16(int32_t s, uint32_t gain)
{
    return (uint32_t)((int32_t)((uint32_t)s * (gain >> GAIN_SHIFT)) >> SAMPLE16_SHIFT);
}

void sound_mix_mono16(MixVoice *v, int32_t *acc, uint32_t count)
{
    uint32_t pos = v->pos, frac = v->frac;
    for (uint32_t i = 0; i < count; i++) {
        const int32_t s = sample16(v->data, pos);
        acc[2 * i] = (int32_t)((uint32_t)acc[2 * i] + scaled16(s, v->gains.left));
        acc[2 * i + 1] = (int32_t)((uint32_t)acc[2 * i + 1] + scaled16(s, v->gains.right));
        advance(v, &pos, &frac);
    }
    v->pos = pos;
    v->frac = frac;
}

void sound_mix_stereo8(MixVoice *v, int32_t *acc, uint32_t count)
{
    uint32_t pos = v->pos, frac = v->frac;
    for (uint32_t i = 0; i < count; i++) {
        acc[2 * i] = (int32_t)((uint32_t)acc[2 * i] + (uint32_t)volume_row(v->gains.left, v->data[2 * pos]));
        acc[2 * i + 1] = (int32_t)((uint32_t)acc[2 * i + 1] + (uint32_t)volume_row(v->gains.right, v->data[2 * pos + 1]));
        advance(v, &pos, &frac);
    }
    v->pos = pos;
    v->frac = frac;
}

void sound_mix_stereo16(MixVoice *v, int32_t *acc, uint32_t count)
{
    uint32_t pos = v->pos, frac = v->frac;
    for (uint32_t i = 0; i < count; i++) {
        acc[2 * i] = (int32_t)((uint32_t)acc[2 * i] + scaled16(sample16(v->data, 2 * pos), v->gains.left));
        acc[2 * i + 1] = (int32_t)((uint32_t)acc[2 * i + 1] + scaled16(sample16(v->data, 2 * pos + 1), v->gains.right));
        advance(v, &pos, &frac);
    }
    v->pos = pos;
    v->frac = frac;
}

/* 0049808a / 004980d4's frames to a mark: (mark - pos, 0 if past it) << 24
 * over the step (div edx:eax; the fraction is not counted). The original
 * faults when the step is 0 or the quotient passes 32 bits; the port gives
 * 0 for the first and keeps the low word of the second. */
static uint32_t frames_to(const MixVoice *v, uint32_t mark)
{
    const int32_t diff = (int32_t)(mark - v->pos);
    if (v->step.step == 0) return 0;
    return (uint32_t)(((uint64_t)(uint32_t)(diff < 0 ? 0 : diff) << STEP_FRACTION_BITS) / v->step.step);
}

static int32_t at_most(uint32_t frames, int32_t left)
{
    return (int32_t)frames < left ? (int32_t)frames : left;
}

int32_t sound_span_once(MixVoice *v, int32_t left)
{
    const uint32_t frames = frames_to(v, v->end);
    if (frames == 0) {
        v->on = 0;
        return 0;
    }
    return at_most(frames, left);
}

int32_t sound_span_loop(MixVoice *v, int32_t left)
{
    uint32_t frames = frames_to(v, v->loop_end);
    if (frames == 0) {
        v->pos = v->loop_start;
        v->frac = 0;
        frames = frames_to(v, v->loop_end);
        if (frames == 0) return 0; /* the original loops forever */
    }
    return at_most(frames, left);
}
