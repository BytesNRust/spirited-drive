int32_t key_code(uint16_t key)
{
    const uint8_t high = (uint8_t)(key >> 8);
    const uint8_t wanted = high != 0 ? (uint8_t)(high | 0x80) : (uint8_t)key;
    for (int32_t i = 0; i < KEY_ROWS * KEY_ROW; i++)
        if (KEY_CHARS[i] == wanted) return (i + 1) % KEY_ROW - 1;
    return 0;
}
