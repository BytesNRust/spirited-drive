#!/usr/bin/env python3
"""Writes game/sys/data_manifest.c: the sizes and SHA-256 of the key files of The Need for Speed SE (PC) that the first-run wizard checks a chosen folder
against (data_check.h). usage: gen_data_manifest.py <the CD's files> > game/sys/data_manifest.c"""
import hashlib, os, sys

KEY = [
    "NFS_WIN.EXE",
    "SIMDATA/MISC/AL1.TRI",
    "SIMDATA/MISC/CL1.TRI",
    "SIMDATA/MISC/TR1.TRI",
    "SIMDATA/CARFAMS/P911.CFM",
    "SIMDATA/CARFAMS/TSUPRA.CFM",
    "SIMDATA/CARFAMS/TRAFFC.CFM",
    "SIMDATA/CARSPECS/P911.PBS",
    "SIMDATA/GDASH/ANSXDH.FSH",
    "SIMDATA/ETRACKFM/AL1_001.FAM",
    "FRONTEND/ART/CREDITS.QFS",
    "FRONTEND/MUSIC/PAUSE.ASF",
]

root = sys.argv[1]
print("/* generated by tools/gen_data_manifest.py from the PC SE CD: do not edit */")
print('#include "game/sys/data_check.h"\n')
print("const DataFile DATA_MANIFEST[] = {")
for rel in KEY:
    path = os.path.join(root, rel)
    data = open(path, "rb").read()
    print('    { "%s", %d, "%s" },' % (rel, len(data), hashlib.sha256(data).hexdigest()))
print("};")
print("const int DATA_MANIFEST_COUNT = (int)(sizeof DATA_MANIFEST / sizeof DATA_MANIFEST[0]);")
