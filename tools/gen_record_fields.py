#!/usr/bin/env python3
"""Writes core/formats/pbs_fields.c: the RecordField table of the PBS record for the TSV exchange, from
docs/car_specs.tsv (the same source as game/race/car_specs.h). Gaps between named fields become byte runs.
    gen_record_fields.py"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_car_struct as g  # noqa: E402

KINDS = {"i32": "REC_I32", "u32": "REC_U32", "i16": "REC_I16", "u16": "REC_U16", "i8": "REC_I8", "u8": "REC_U8",
         "ref": "REC_U32", "angle": "REC_I32"}
SIZE = 0x778


def main():
    fields = g.parse(ROOT / "docs/car_specs.tsv", SIZE)
    out = ["/* Generated by tools/gen_record_fields.py from docs/car_specs.tsv; edit that. */",
           '#include "formats/pbs.h"', "", "const RecordField pbs_fields[] = {"]
    pos = 0
    rows = []

    def pad(start, end):
        # the checksum word is a field of its own; everything else unnamed is an opaque byte run
        rows.append(f'    {{ {start:#x}, REC_BYTES, {end - start}, "pad_{start:03x}" }},')

    for off, ctype, size_of, count, name, note, typ in fields:
        if off > pos:
            pad(pos, off)
        kind = KINDS[typ if "[" not in typ else typ.split("[")[0]]
        if name.startswith("pad") or (typ.startswith("u8") and count > 1):
            kind, cnt = "REC_BYTES", count * size_of
        else:
            cnt = count
        rows.append(f'    {{ {off:#x}, {kind}, {cnt}, "{name}" }},')
        pos = off + size_of * count
    if pos < SIZE:
        pad(pos, SIZE)
    out += rows + ["};", "", "const size_t pbs_field_count = sizeof pbs_fields / sizeof pbs_fields[0];", ""]
    (ROOT / "core/formats/pbs_fields.c").write_text("\n".join(out))


if __name__ == "__main__":
    main()
