#!/usr/bin/env python3
"""Generates the packed records of the car simulation from their field
tables: the original's byte layout, named fields where known and padding
elsewhere, plus a field table.
    gen_car_struct.py            both records below
    gen_car_struct.py TSV OUT NAME SIZE"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECORDS = [("docs/car_fields.tsv", "src/game/race/car_struct.h", "Car", 0x79A),
           ("docs/car_specs.tsv", "src/game/race/car_specs.h", "CarSpecs", 0x778)]
TYPES = {"i32": ("int32_t", 4), "u32": ("uint32_t", 4), "i16": ("int16_t", 2), "u16": ("uint16_t", 2),
         "i8": ("int8_t", 1), "u8": ("uint8_t", 1), "ref": ("uint32_t", 4), "angle": ("int32_t", 4)}


def parse(path, size):
    fields = []
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t")
        off, typ, name = int(cols[0], 16), cols[1], cols[2]
        note = cols[3] if len(cols) > 3 else ""
        count = 1
        if "[" in typ:
            typ, n = typ[:-1].split("[")
            count = int(n)
        ctype, size_of = TYPES[typ]
        fields.append((off, ctype, size_of, count, name, note, typ))
    fields.sort()
    for a, b in zip(fields, fields[1:]):
        if a[0] + a[2] * a[3] > b[0]:
            raise SystemExit(f"{a[4]} at {a[0]:#x} overlaps {b[4]} at {b[0]:#x}")
    if fields and fields[-1][0] + fields[-1][2] * fields[-1][3] > size:
        raise SystemExit("past the end of the record")
    return fields


def snake(name):
    return "".join("_" + c.lower() if c.isupper() and i else c.lower() for i, c in enumerate(name))


def generate(fields, tsv, out_path, name, size):
    upper = snake(name).upper()
    guard = "TNFS_" + Path(out_path).stem.upper() + "_H"
    out = [f"/* Generated by tools/gen_car_struct.py from {tsv}; edit that. */",
           f"#ifndef {guard}", f"#define {guard}", "", "#include <stddef.h>",
           "#include <stdint.h>", "", f"enum {{ {upper}_SIZE = {size:#x} }};", "",
           "#pragma pack(push, 1)", "typedef struct {"]
    pos = 0
    for off, ctype, fsize, count, fname, note, typ in fields:
        if off > pos:
            out.append(f"    uint8_t pad_{pos:03x}[{off - pos:#x}];")
        dim = f"[{count}]" if count > 1 else ""
        comment = f"  /* {off:#05x} {note} */" if note else f"  /* {off:#05x} */"
        out.append(f"    {ctype} {fname}{dim};{comment}")
        pos = off + fsize * count
    if pos < size:
        out.append(f"    uint8_t pad_{pos:03x}[{size - pos:#x}];")
    check = f"{upper}_CHECK"
    out += [f"}} {name};", "#pragma pack(pop)", "",
            "/* C99 compile-time checks: a negative array size fails the build. */",
            f"#define {check}(field, cond) typedef char {snake(name)}_check_##field[(cond) ? 1 : -1]",
            f"{check}(size, sizeof({name}) == {upper}_SIZE);"]
    for off, ctype, fsize, count, fname, note, typ in fields:
        out.append(f"{check}({fname}, offsetof({name}, {fname}) == {off:#x});")
    out += ["", "#endif", ""]
    return "\n".join(out)


def main():
    records = RECORDS
    if len(sys.argv) > 4:
        records = [(sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4], 0))]
    for tsv, out, name, size in records:
        (ROOT / out).write_text(generate(parse(ROOT / tsv, size), tsv, out, name, size))


if __name__ == "__main__":
    main()
