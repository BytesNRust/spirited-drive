#!/usr/bin/env python3
"""Generates src/game/race/car_struct.h from docs/car_fields.tsv: the car
record with the original's byte layout (packed), named fields where known and
padding elsewhere, plus a field table the oracle uses to compare records.
    gen_car_struct.py [TSV] [OUT]"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIZE = 0x79A
TYPES = {"i32": ("int32_t", 4), "u32": ("uint32_t", 4), "i16": ("int16_t", 2), "u16": ("uint16_t", 2),
         "i8": ("int8_t", 1), "u8": ("uint8_t", 1), "ref": ("uint32_t", 4), "angle": ("int32_t", 4)}


def parse(path):
    fields = []
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t")
        off, typ, name = int(cols[0], 16), cols[1], cols[2]
        note = cols[3] if len(cols) > 3 else ""
        count = 1
        if "[" in typ:
            typ, n = typ[:-1].split("[")
            count = int(n)
        ctype, size = TYPES[typ]
        fields.append((off, ctype, size, count, name, note, typ))
    fields.sort()
    for a, b in zip(fields, fields[1:]):
        if a[0] + a[2] * a[3] > b[0]:
            raise SystemExit(f"{a[4]} at {a[0]:#x} overlaps {b[4]} at {b[0]:#x}")
    if fields and fields[-1][0] + fields[-1][2] * fields[-1][3] > SIZE:
        raise SystemExit("past the end of the record")
    return fields


def generate(fields):
    out = ["/* Generated by tools/gen_car_struct.py from docs/car_fields.tsv; edit those. */",
           "#ifndef TNFS_CAR_STRUCT_H", "#define TNFS_CAR_STRUCT_H", "", "#include <stddef.h>",
           "#include <stdint.h>", "", f"enum {{ CAR_RECORD_SIZE = {SIZE:#x} }};", "",
           "#pragma pack(push, 1)", "typedef struct {"]
    pos = 0
    for off, ctype, size, count, name, note, typ in fields:
        if off > pos:
            out.append(f"    uint8_t pad_{pos:03x}[{off - pos:#x}];")
        dim = f"[{count}]" if count > 1 else ""
        comment = f"  /* {off:#05x} {note} */" if note else f"  /* {off:#05x} */"
        out.append(f"    {ctype} {name}{dim};{comment}")
        pos = off + size * count
    if pos < SIZE:
        out.append(f"    uint8_t pad_{pos:03x}[{SIZE - pos:#x}];")
    out += ["} Car;", "#pragma pack(pop)", "",
            "/* C99 compile-time checks: a negative array size fails the build. */",
            "#define CAR_CHECK(name, cond) typedef char car_check_##name[(cond) ? 1 : -1]",
            "CAR_CHECK(size, sizeof(Car) == CAR_RECORD_SIZE);"]
    for off, ctype, size, count, name, note, typ in fields:
        out.append(f"CAR_CHECK({name}, offsetof(Car, {name}) == {off:#x});")
    out += ["", "/* Every named field: the oracle compares these; refs are skipped. */",
            "typedef struct {", "    const char *name;", "    uint16_t offset, size;", "    uint8_t is_ref;",
            "} CarField;", "", "static const CarField CAR_FIELDS[] = {"]
    for off, ctype, size, count, name, note, typ in fields:
        out.append(f"    {{ \"{name}\", {off:#x}, {size * count}, {int(typ == 'ref')} }},")
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


def main():
    tsv = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "docs/car_fields.tsv"
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "src/game/race/car_struct.h"
    out.write_text(generate(parse(tsv)))


if __name__ == "__main__":
    main()
