# check_release_notes.sh [RELEASE_NOTES.md]: a release must not go out with the draft's placeholders. Fails (exit 1) while the file still holds "DRAFT", "[X.Y.Z]" or "[WIN]"
# (the markers a draft of the notes carries until the owner has written the real text), saying which and where. A file that is not there passes with a notice
# (the release workflow then lets GitHub generate the notes). Exit 2 for bad arguments.
set -eu
[ $# -le 1 ] || { echo "usage: $0 [RELEASE_NOTES.md]" >&2; exit 2; }
notes=${1:-RELEASE_NOTES.md}
if [ ! -f "$notes" ]; then
    echo "no $notes: the release notes will be generated by GitHub"
    exit 0
fi
found=0
for marker in 'DRAFT' '[X.Y.Z]' '[WIN]'; do
    lines=$(grep -n -F -- "$marker" "$notes" | head -n 3 || true)
    if [ -n "$lines" ]; then
        found=1
        echo "::error file=$notes::$notes still contains the placeholder $marker; the owner writes the real text before a tag is pushed:" >&2
        echo "$lines" | sed 's/^/  line /' >&2
    fi
done
if [ "$found" = 1 ]; then
    echo "::error::the release notes are still a draft: finish $notes in the commit that is tagged (notes/runbook-release.md, section 3), then delete the draft release and the tag and tag the new commit" >&2
    exit 1
fi
echo "$notes has no draft placeholder"
